const useStoreData = (storeId, storeProp) => {
  const cacheKey = `pos_store_${storeId}`;
  const [storeData, setStoreData] = useState(() => {
    if (storeProp?.storeName || storeProp?.name) return storeProp;
    const cached = safeJSON(cacheKey);
    if (cached && (cached.storeName || cached.name) &&
      Date.now() - (cached._cachedAt || 0) < CACHE_TTL_MS) return cached;
    return null;
  });

  useEffect(() => {
    if (storeProp?.storeName || storeProp?.name) { setStoreData(storeProp); return; }
    if (!storeId || storeId === 'default' || !navigator.onLine) return;
    const unsub = onSnapshot(
      doc(db, 'stores', storeId),
      (snap) => {
        if (!snap.exists()) return;
        const data = { id: snap.id, ...snap.data(), _cachedAt: Date.now() };
        setStoreData(data);
        try { localStorage.setItem(cacheKey, JSON.stringify(data)); } catch { }
      },
      () => { },
    );
    return () => unsub();
  }, [storeId, storeProp, cacheKey]);

  return storeData;
};

