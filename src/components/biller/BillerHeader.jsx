const formatAmount = (amount) =>
  Number(amount || 0).toLocaleString('en-PK', { maximumFractionDigits: 0 });

const fmtDate = (value) => {
  const d = toSafeDate(value);
  if (!d) return '--';
  return d.toLocaleDateString('en-PK', {
    day: '2-digit', month: 'short', year: 'numeric',
  });
};

const fmtTime = (value) => {
  const d = toSafeDate(value);
  if (!d) return '--';
  return d.toLocaleTimeString('en-PK', {
    hour: '2-digit', minute: '2-digit', hour12: true,
  });
};

const ROLE_ICON_MAP = { Crown, ShieldCheck, Users, Receipt, CreditCard };

const getRoleIcon = (role) => {
  const iconName = ROLE_INFO?.[role]?.icon;
  return ROLE_ICON_MAP[iconName] || Receipt;
};

const toMs = (value) => {
  if (!value) return 0;
  try {
    if (value?.toDate) return value.toDate().getTime();
    if (value?.seconds) return value.seconds * 1000;
    if (typeof value === 'number') return value;
    const d = new Date(value);
    return isNaN(d) ? 0 : d.getTime();
  } catch { return 0; }
};

const safeJSON = (key) => {
  try { return JSON.parse(localStorage.getItem(key)); }
  catch { return null; }
};

const getCustomerLabel = (order) => {
  if (!order) return 'Walk-in';
  const c = order.customer || { name: order.customerName, phone: order.customerPhone };
  return resolveCustomerName(c);
};

